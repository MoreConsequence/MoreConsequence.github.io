-- 建库建表：造一张 20 万行的表，作为 DDL 与 MDL 的实验对象。
-- 运行：mysql -u root < experiments/mysql-ddl/01_setup.sql
-- 说明：表的规模刻意做小（20 万行），让 INPLACE 的构建段快速走完，
--       把实验焦点集中在 MDL 的排队窗口上，而不是重建耗时。

CREATE DATABASE IF NOT EXISTS ddl_demo;
USE ddl_demo;

DROP TABLE IF EXISTS big_table;
CREATE TABLE big_table (
  id   INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  val  INT NOT NULL,
  pad  CHAR(64) NOT NULL DEFAULT ''
) ENGINE=InnoDB;

-- 交叉连接生成 20 万行（10^5 * 2），不依赖 RAND() 的随机性。
INSERT INTO big_table (val, pad)
SELECT seq, REPEAT('x', 64)
FROM (
  SELECT a.n + b.n*10 + c.n*100 + d.n*1000 + e.n*10000 + f.n*200000 AS seq
  FROM
    (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
     UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) a
  CROSS JOIN (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
     UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) b
  CROSS JOIN (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
     UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) c
  CROSS JOIN (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
     UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) d
  CROSS JOIN (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
     UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) e
  CROSS JOIN (SELECT 0 n UNION ALL SELECT 1) f
) nums;

SELECT COUNT(*) AS rows_cnt, MAX(id) AS max_id FROM big_table;  -- 期望 200000 / 200000
